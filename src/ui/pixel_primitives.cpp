// ==[ FAT LINE 4PX ]== Bresenham with 4px cell coverage
void fatLine4(M5Canvas& c, int x0, int y0, int x1, int y1, uint16_t col) {
    x0 = q4(x0); y0 = q4(y0); x1 = q4(x1); y1 = q4(y1);
    int dx = abs(x1 - x0), sx = x0 < x1 ? 4 : -4;
    int dy = -abs(y1 - y0), sy = y0 < y1 ? 4 : -4;
    int err = dx + dy, e2;

    while (true) {
        // Gfx::fastFillBlock4 is unchecked (perf) and needs an in-bounds,
        // 4-aligned block. Clip here so an off-canvas endpoint cannot write
        // outside the canvas buffer.
        if (x0 >= 0 && x0 <= c.width() - 4 && y0 >= 0 && y0 <= c.height() - 4)
            Gfx::fastFillBlock4(c, x0, y0, col);
        if (x0 == x1 && y0 == y1) break;
        e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

// ==[ FAT LINE 2PX ]==
void fatLine2(M5Canvas& c, int x0, int y0, int x1, int y1, uint16_t col) {
    x0 = q2(x0); y0 = q2(y0); x1 = q2(x1); y1 = q2(y1);
    int dx = abs(x1 - x0), sx = x0 < x1 ? 2 : -2;
    int dy = -abs(y1 - y0), sy = y0 < y1 ? 2 : -2;
    int err = dx + dy, e2;

    while (true) {
        Gfx::fastFillBlock2(c, x0, y0, col);
        if (x0 == x1 && y0 == y1) break;
        e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

// ==[ CIRCLE 4PX ]== Midpoint circle, draws 4px blocks at octants
void circle4(M5Canvas& c, int cx, int cy, int r, uint16_t col) {
    cx = q4(cx); cy = q4(cy); r = q4(r);
    int x = 0, y = r;
    int d = 3 - 2 * r;
    auto drawOctants = [&](int x, int y) {
        Gfx::fastFillBlock4(c, cx + x, cy + y, col);
        Gfx::fastFillBlock4(c, cx - x, cy + y, col);
        Gfx::fastFillBlock4(c, cx + x, cy - y, col);
        Gfx::fastFillBlock4(c, cx - x, cy - y, col);
        Gfx::fastFillBlock4(c, cx + y, cy + x, col);
        Gfx::fastFillBlock4(c, cx - y, cy + x, col);
        Gfx::fastFillBlock4(c, cx + y, cy - x, col);
        Gfx::fastFillBlock4(c, cx - y, cy - x, col);
    };
    drawOctants(x, y);
    while (y >= x) {
        x += 4;
        if (d > 0) { y -= 4; d = d + 4 * (x - y) + 10; }
        else { d = d + 4 * x + 6; }
        drawOctants(x, y);
    }
}

// ==[ ELLIPSE 4PX ]== Midpoint ellipse
void ellipse4(M5Canvas& c, int cx, int cy, int rx, int ry, uint16_t col) {
    cx = q4(cx); cy = q4(cy); rx = q4(rx); ry = q4(ry);
    int x = 0, y = ry;
    int rx2 = rx * rx, ry2 = ry * ry;
    int twoRx2 = 2 * rx2, twoRy2 = 2 * ry2;
    int px = 0, py = twoRx2 * y;

    auto plot = [&](int x, int y) {
        Gfx::fastFillBlock4(c, cx + x, cy + y, col);
        Gfx::fastFillBlock4(c, cx - x, cy + y, col);
        Gfx::fastFillBlock4(c, cx + x, cy - y, col);
        Gfx::fastFillBlock4(c, cx - x, cy - y, col);
    };

    // Region 1
    int d = ry2 - rx2 * ry + rx2 / 4;
    while (px < py) {
        plot(x, y);
        x += 4; px += twoRy2;
        if (d < 0) d += ry2 + px;
        else { y -= 4; py -= twoRx2; d += ry2 + px - py; }
    }
    // Region 2
    d = (int)(ry2 * (x + 2) * (x + 2) + rx2 * (y - 2) * (y - 2) - rx2 * ry2);
    while (y >= 0) {
        plot(x, y);
        y -= 4; py -= twoRx2;
        if (d > 0) d += rx2 - py;
        else { x += 4; px += twoRy2; d += rx2 - py + px; }
    }
}

// ==[ ROUNDED RECT 4PX ]== 4px corner radius
void roundRect4(M5Canvas& c, int x, int y, int w, int h, uint16_t col) {
    x = q4(x); y = q4(y); w = q4(w); h = q4(h);
    if (w < 8 || h < 8) { fillRect4(c, x, y, w, h, col); return; }
    int r = 4;
    // Top/bottom edges (excluding corners)
    fillRect4(c, x + r, y, w - 2 * r, r, col);
    fillRect4(c, x + r, y + h - r, w - 2 * r, r, col);
    // Middle
    fillRect4(c, x, y + r, w, h - 2 * r, col);
    // Corners (4 quadrants of 4px circle)
    for (int dy = 0; dy < r; dy += 4) {
        int dx = (int)sqrtf(r * r - dy * dy);
        dx = q4(dx);
        // TL
        fillRect4(c, x + r - dx, y + dy, dx, 4, col);
        // TR
        fillRect4(c, x + w - r, y + dy, dx, 4, col);
        // BL
        fillRect4(c, x + r - dx, y + h - r - dy, dx, 4, col);
        // BR
        fillRect4(c, x + w - r, y + h - r - dy, dx, 4, col);
    }
}

// ==[ TRIANGLES ]== Flat bottom/top, grid-snapped
void triangleFlatBottom4(M5Canvas& c, int x1, int y1, int x2, int y2, int x3, int y3, uint16_t col) {
    // y1==y2 (top edge), y3 > y1 (bottom vertex)
    x1 = q4(x1); y1 = q4(y1); x2 = q4(x2); y2 = q4(y2); x3 = q4(x3); y3 = q4(y3);
    float invSlope1 = (float)(x3 - x1) / (y3 - y1);
    float invSlope2 = (float)(x3 - x2) / (y3 - y2);
    float curX1 = x1, curX2 = x2;
    for (int y = y1; y <= y3; y += 4) {
        int xl = q4((int)curX1);
        int xr = q4((int)curX2);
        fillRect4(c, xl, y, xr - xl + 4, 4, col);
        curX1 += invSlope1 * 4;
        curX2 += invSlope2 * 4;
    }
}
void triangleFlatTop4(M5Canvas& c, int x1, int y1, int x2, int y2, int x3, int y3, uint16_t col) {
    // y2==y3 (bottom edge), y1 < y2 (top vertex)
    x1 = q4(x1); y1 = q4(y1); x2 = q4(x2); y2 = q4(y2); x3 = q4(x3); y3 = q4(y3);
    float invSlope1 = (float)(x2 - x1) / (y2 - y1);
    float invSlope2 = (float)(x3 - x1) / (y3 - y1);
    float curX1 = x1, curX2 = x1;
    for (int y = y1; y <= y2; y += 4) {
        int xl = q4((int)curX1);
        int xr = q4((int)curX2);
        fillRect4(c, xl, y, xr - xl + 4, 4, col);
        curX1 += invSlope1 * 4;
        curX2 += invSlope2 * 4;
    }
}

