void drawBlockGlyph5x7(M5Canvas& c, int cx, int cy, char ch, int cell,
                       const GlyphLayer* layers, int nLayers) {
    if (ch < 32 || ch > 127) ch = '?';
    const uint8_t* glyph = kFont5x7[ch - 32];
    int x0 = cx - (5 * cell) / 2;
    int y0 = cy - (7 * cell) / 2;
    x0 = q4(x0); y0 = q4(y0);
    for (int row = 0; row < 7; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 5; col++) {
            if ((bits & (0x10 >> col)) == 0) continue;
            int px = x0 + col * cell;
            int py = y0 + row * cell;
            for (int l = 0; l < nLayers; l++) {
                int lx = px + layers[l].dx * cell;
                int ly = py + layers[l].dy * cell;
                if (cell == 4) Gfx::fastFillBlock4(c, lx, ly, layers[l].color);
                else Gfx::fastFillBlock2(c, lx, ly, layers[l].color);
            }
        }
    }
}

void drawBlockText5x7(M5Canvas& c, int cx, int cy, const char* text, int cell,
                      const GlyphLayer* layers, int nLayers, int spacing) {
    int len = strlen(text);
    int totalW = len * 5 * cell + (len - 1) * spacing;
    int x = cx - totalW / 2;
    x = q4(x);
    for (int i = 0; i < len; i++) {
        drawBlockGlyph5x7(c, x + (5 * cell) / 2 + i * (5 * cell + spacing), cy,
                          text[i], cell, layers, nLayers);
    }
}

